"""Keep docs/KNOWLEDGE_BASE.md in sync with the code.

Regenerates the block between the AUTO:AT-A-GLANCE markers from the source of truth:
test counts (pytest collection, Playwright --list), API endpoints, pages, database tables,
user stories by status and the RAG lab baseline.

  python scripts/update_kb.py           # rewrite the block
  python scripts/update_kb.py --check   # CI: fail if the block is out of date
"""
import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KB = ROOT / "docs" / "KNOWLEDGE_BASE.md"
START, END = "<!-- AUTO:AT-A-GLANCE:START -->", "<!-- AUTO:AT-A-GLANCE:END -->"


def run(cmd: list[str], cwd: Path = ROOT) -> str:
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, encoding="utf-8", errors="replace").stdout


def pytest_counts() -> dict[str, int]:
    """Collected tests per folder (unit / api / db)."""
    out = run([sys.executable, "-m", "pytest", "--collect-only", "-q"])
    per_file: dict[str, int] = {}
    for line in out.splitlines():
        line = line.strip().replace("\\", "/")
        summary = re.match(r"^(tests/\S+\.py): (\d+)$", line)        # "-qq" style: one line per file
        if summary:
            per_file[summary.group(1)] = int(summary.group(2))
        elif "::" in line and line.startswith("tests/"):             # "-q" style: one line per test
            path = line.split("::", 1)[0]
            per_file[path] = per_file.get(path, 0) + 1
    counts = {"total": sum(per_file.values())}
    for layer in ("unit", "api", "db"):
        counts[layer] = sum(n for path, n in per_file.items() if path.startswith(f"tests/{layer}/"))
    return counts


def playwright_counts() -> dict[str, int | None]:
    """Distinct tests in the spec files, plus total runs across projects if Playwright is installed."""
    specs = sorted((ROOT / "e2e" / "tests").glob("*.spec.ts"))
    defined = sum(len(re.findall(r"^\s*test\(", s.read_text(encoding="utf-8"), flags=re.M)) for s in specs)
    runs = None
    npx = shutil.which("npx")
    if npx and (ROOT / "e2e" / "node_modules").exists():
        match = re.search(r"Total:\s*(\d+)\s+tests?", run([npx, "playwright", "test", "--list"], cwd=ROOT / "e2e"))
        runs = int(match.group(1)) if match else None
    return {"specs": len(specs), "defined": defined, "runs": runs}


def routes(path: str) -> list[str]:
    text = (ROOT / path).read_text(encoding="utf-8")
    return [f"{m.upper()} {p}" for m, p in re.findall(r'@router\.(get|post|put|patch|delete)\("([^"]+)"', text)]


def tables() -> list[str]:
    return re.findall(r'__tablename__ = "([a-z_]+)"', (ROOT / "app" / "models.py").read_text(encoding="utf-8"))


def stories() -> dict[str, int]:
    text = (ROOT / "docs" / "REQUIREMENTS.md").read_text(encoding="utf-8")
    heads = re.findall(r"^## US-\d+ .*$", text, flags=re.M)
    return {"total": len(heads), "done": sum("(Done" in h for h in heads), "planned": sum("(Planned" in h for h in heads)}


def rag_baseline() -> str:
    sys.path.insert(0, str(ROOT))
    from ai.rag_lab.eval import evaluate
    r1, r3 = evaluate(k=1), evaluate(k=3)
    return f"recall@1 {r1['recall_at_k']:.0%}, recall@3 {r3['recall_at_k']:.0%} on {len(r3['rows'])} golden questions"


def build_block() -> str:
    py, pw, st = pytest_counts(), playwright_counts(), stories()
    api, pages = routes("app/routers/api.py"), routes("app/routers/pages.py")
    pw_runs = f"{pw['runs']} runs across desktop + mobile projects" if pw["runs"] else "runs counted when Playwright is installed"
    rows = [
        ("User stories", f"{st['total']} ({st['done']} done, {st['planned']} planned, rest vision)"),
        ("pytest tests", f"{py['total']} (unit {py['unit']}, API {py['api']}, DB {py['db']})"),
        ("Playwright tests", f"{pw['defined']} in {pw['specs']} spec files; {pw_runs}"),
        ("JSON API endpoints", str(len(api))),
        ("HTML page routes", str(len(pages))),
        ("Database tables", f"{len(tables())}: {', '.join(tables())}"),
        ("RAG lab baseline", rag_baseline()),
    ]
    table = "\n".join(f"| {k} | {v} |" for k, v in rows)
    endpoints = "\n".join(f"- `{e}`" for e in api)
    return (f"{START}\n_Generated by `scripts/update_kb.py` from the code. Do not edit by hand; CI fails if it is stale._\n\n"
            f"| Item | Now |\n|---|---|\n{table}\n\n<details><summary>All {len(api)} API endpoints</summary>\n\n{endpoints}\n\n</details>\n{END}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = KB.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print("Markers not found in docs/KNOWLEDGE_BASE.md"); return 1
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: build_block(), text, flags=re.S)
    if args.check:
        if new != text:
            print("docs/KNOWLEDGE_BASE.md is out of date. Run: python scripts/update_kb.py, then commit."); return 1
        print("Knowledge base is up to date."); return 0
    KB.write_text(new, encoding="utf-8")
    print("Updated docs/KNOWLEDGE_BASE.md"); return 0


if __name__ == "__main__":
    sys.exit(main())
